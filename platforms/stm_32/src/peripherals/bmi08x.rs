const SPI_READ: u8 = 0x80;
const SPI_WRITE: u8 = 0x00;

pub struct Bmi08xSensor {
    pub dev_a: SpiDevice<
        'static,
        CriticalSectionRawMutex,
        spi::Spi<'static, Async, spi::mode::Master>,
        Output<'static>,
    >,
    pub dev_g: SpiDevice<
        'static,
        CriticalSectionRawMutex,
        spi::Spi<'static, Async, spi::mode::Master>,
        Output<'static>,
    >,

    pub sample_rate: SampleRate,

    pub drdy_a: ExtiInput<'static, Async>,
    pub drdy_g: ExtiInput<'static, Async>,
    pub jumper: Output<'static>,

    pub range_a: AccelRange,
    pub range_g: GyroRange,
    /// Fixed sensor-to-board axis signs, applied before configurable IMU rotation and calibration.
    pub board_axis_signs: [f64; 3],
}

impl Bmi08xSensor {
    async fn read_register_a(&mut self, reg_addr: u8) -> u8 {
        let tx = [reg_addr | SPI_READ, 0x00, 0x00];
        let mut rx = [0u8; 3];
        let _ = self.dev_a.transfer(&mut rx, &tx).await;
        rx[2]
    }
    async fn read_register_g(&mut self, reg_addr: u8) -> u8 {
        let tx = [reg_addr | SPI_READ, 0x00];
        let mut rx = [0u8; 2];
        let _ = self.dev_g.transfer(&mut rx, &tx).await;
        rx[1]
    }

    async fn write_register_a(&mut self, reg_addr: u8, value: u8) {
        let tx = [reg_addr | SPI_WRITE, value];
        let _ = self.dev_a.write(&tx).await; // Soft Reset
    }

    async fn write_register_g(&mut self, reg_addr: u8, value: u8) {
        let tx = [reg_addr | SPI_WRITE, value];
        let _ = self.dev_g.write(&tx).await; // Soft Reset
    }

    pub async fn run(&mut self) {
        // time for power-on
        Timer::after_millis(50).await;

        const ACCEL_PROD_ID_REG: u8 = 0x00; //BMI08_REG_ACCEL_CHIP_ID
        const ACCEL_PROD_ID_088: u8 = 0x1E;
        const ACCEL_PROD_ID_085: u8 = 0x1F;

        // Check Accel ID  (0x80)
        let _ = self.read_register_a(ACCEL_PROD_ID_REG).await; // Lock to SPI mode

        // Second Read is to get the ID
        let accel_id = self.read_register_a(ACCEL_PROD_ID_REG).await;
        let mut accel_range: f64 = 0f64;

        if accel_id == ACCEL_PROD_ID_088 {
            accel_range = match &self.range_a {
                AccelRange::Bmi088(range) => {
                    3.0 * ((0x0001 << (*range as u32)) as f64) * 9.80665f64
                }
                AccelRange::Bmi085(range) => {
                    2.0 * ((0x0001 << (*range as u32)) as f64) * 9.80665f64
                }
            };
        } else if accel_id == ACCEL_PROD_ID_085 {
            accel_range = match &self.range_a {
                AccelRange::Bmi088(range) => {
                    3.0 * ((0x0001 << (*range as u32)) as f64) * 9.80665f64
                }
                AccelRange::Bmi085(range) => {
                    2.0 * ((0x0001 << (*range as u32)) as f64) * 9.80665f64
                }
            };
        }

        const GYRO_PROD_ID_REG: u8 = 0x00; // BMI08_REG_GYRO_CHIP_ID
        const GYRO_PROD_ID: u8 = 0x0F;

        // Second Read is to get the ID
        let gyro_id = self.read_register_g(GYRO_PROD_ID_REG).await;
        let mut gyro_range: f64 = 0f64;

        if gyro_id == GYRO_PROD_ID {
            gyro_range = match &self.range_g {
                GyroRange::Max125dps => 125.0f64,
                GyroRange::Max250dps => 250.0f64,
                GyroRange::Max500dps => 500.0f64,
                GyroRange::Max1000dps => 1000.0f64,
                GyroRange::Max2000dps => 2000.0f64,
            } * 0.017453292519943295f64;
        }

        // Accel Soft Reset (0x7E, 0xB6) //BMI08_REG_ACCEL_SOFTRESET
        self.write_register_a(0x7E, 0xB6).await;
        Timer::after_micros(1000).await; // required

        // Lock to SPI mode again (after soft reset)
        self.read_register_a(ACCEL_PROD_ID_REG).await;
        Timer::after_micros(4900).await; // not needed? It's in the Bosh code

        // Activate Accel (0x7C,0x00) //BMI08_REG_ACCEL_PWR_CONF
        self.write_register_a(0x7C, 0x00).await;
        Timer::after_micros(450).await; // required

        // Disable "Config Loading" (0x59, 0x00) // BMI08_REG_ACCEL_INIT_CTRL
        self.write_register_a(0x59, 0x00).await;

        // Write Sensor Program
        const BLOCK_SIZE: usize = 32;
        for (index, block) in BMI_CONFIG.chunks(BLOCK_SIZE).enumerate() {
            self.write_register_a(0x5B, 0x00).await; //BMI08_REG_ACCEL_RESERVED_5B
            self.write_register_a(0x5C, index as u8).await; //BMI08_REG_ACCEL_RESERVED_5C
            let mut tx = [0u8; BLOCK_SIZE + 1];
            tx[0] = 0x5E | SPI_WRITE; // BMI08_REG_ACCEL_FEATURE_CFG
            for (i, &item) in block.iter().enumerate() {
                tx[i + 1] = item;
            }
            let _ = self.dev_a.write(&tx).await;
        }

        // Re-enable "Config Loading"
        self.write_register_a(0x59, 0x01).await;
        Timer::after_micros(150000).await; // required?

        // Unknown status register read (0x2A|SPI_READ)
        // BMI08_REG_ACCEL_INIT_CTRL = 0x2A   (0xAA)
        let _ = self.read_register_a(0x2A).await;

        // Activate Accel, again (0x7C,0x00)
        // BMI08_REG_ACCEL_PWR_CONF = 0x7C
        self.write_register_a(0x7C, 0x00).await;
        Timer::after_micros(450).await; // required, was 5000us, using 450us like above

        // Accelerometer ON (0x7D,0x04)
        // BMI08_REG_ACCEL_PWR_CTRL = 0x7D
        self.write_register_a(0x7D, 0x04).await; //
        Timer::after_micros(100).await;

        // Read/Write Low Power Mode
        // BMI08_REG_GYRO_LPM1 = 0x11 (0x91)
        let _ = self.read_register_g(0x11).await;
        self.write_register_g(0x11, 0x00).await;
        Timer::after_millis(30).await;

        // Read/Write Gyro Bandwidth
        // BMI08_REG_GYRO_BANDWIDTH = 0x10 (0x90)
        let gyro_bw = match self.sample_rate {
            SampleRate::Odr2000Hz => GyroBandwidth::Odr2000Hz as u8,
            SampleRate::Odr1000Hz => GyroBandwidth::Odr1000Hz as u8,
            SampleRate::Odr400Hz => GyroBandwidth::Odr400Hz as u8,
        };
        let _ = self.read_register_g(0x10).await;
        self.write_register_g(0x10, gyro_bw).await;

        // Read/Write Gyro Range
        // BMI08_REG_GYRO_RANGE = 0x0F (0x8F)
        let _ = self.read_register_g(0x0F).await;
        self.write_register_g(0x0F, self.range_g as u8).await;
        Timer::after_micros(10000).await; // do we need this delay??

        // Read/Write BMI08_REG_ACCEL_FEATURE_CFG 7+1 bytes
        // This is undocumented, from Bosh drivers
        const BMI08_REG_ACCEL_FEATURE_CFG: u8 = 0x5E; //(0xDE)
        const BMI08_ACCEL_DATA_SYNC_MODE_MASK: u8 = 0x03;
        let mut tx = [0u8; 8];
        let mut sync_cfg = [0u8; 8];
        tx[0] = BMI08_REG_ACCEL_FEATURE_CFG | SPI_READ;
        let _ = self.dev_a.transfer(&mut sync_cfg, &tx).await;

        // Unclear why this is 16-bit data, just following what Bosh does
        sync_cfg[1] = BMI08_REG_ACCEL_FEATURE_CFG | SPI_WRITE; // 0x5E
        let sync_cfg_mode = self.sample_rate as u8;
        let reg_data = sync_cfg_mode & BMI08_ACCEL_DATA_SYNC_MODE_MASK;
        sync_cfg[6] = reg_data; // low byte
        sync_cfg[7] = 0; // high byte
        let _ = self.dev_a.write(&sync_cfg[1..]).await;

        Timer::after_micros(100000).await; // delay of 100ms for data sync to take effect.

        // BMI08_REG_ACCEL_INT2_IO_CONF = 0x54 (0xD4)
        let _ = self.read_register_a(0x54).await;
        self.write_register_a(0x54, 0x13).await; //Int2 as input, active high, reserved[0] = 1
        // BMI08_REG_ACCEL_INT1_MAP = 0x56
        self.write_register_a(0x56, 0x01).await; // undocumented
        // BMI08_INT1_INT2_MAP_DATA = 0x58
        self.write_register_a(0x58, 0x04).await; // !! change, map data ready interrupt to Int1

        // BMI08_REG_ACCEL_INT1_IO_CONF = 0x53 (0xD3)
        let _ = self.read_register_a(0x53).await;
        self.write_register_a(0x53, 0x0A).await; //Int1 as output, active high

        // BMI08_REG_ACCEL_CONF = 0x40
        //	readRegisterA(BMI08_REG_ACCEL_CONF); 		// (0x40)
        //	writeRegisterA(BMI08_REG_ACCEL_CONF, rangeA_);// (0x40,0x0A) Int1 as output, active high

        // BMI08_REG_GYRO_INT3_INT4_IO_MAP = 0x18 (0x98)
        let _ = self.read_register_g(0x18).await;
        self.write_register_g(0x18, 0x81).await; //(0x18,0x80) 0x81 to map drdy to both int3 and int4

        // BMI08_REG_GYRO_INT3_INT4_IO_CONF = 0x16 (0x96)
        let _ = self.read_register_g(0x16).await; // (0x96)
        self.write_register_g(0x16, 0x05).await; // (0x16,0x05)
        //BMI08_REG_GYRO_INT_CTRL = 0x15
        self.write_register_g(0x15, 0x80).await; //(0x15,0x80) Enable drdy interrupt on new data

        // yes this is a repeat sequence
        // BMI08_REG_GYRO_INT3_INT4_IO_MAP = 0x18 (0x98)
        let _ = self.read_register_g(0x18).await;
        self.write_register_g(0x18, 0x81).await; //(0x18,0x80) 0x81 to map drdy to both int3 and int4

        // BMI08_REG_GYRO_INT3_INT4_IO_CONF = 0x16 (0x96)
        let _ = self.read_register_g(0x16).await; // (0x16)
        self.write_register_g(0x16, 0x05).await; // (0x16,0x05)
        //BMI08_REG_GYRO_INT_CTRL = 0x15
        self.write_register_g(0x15, 0x80).await; //(0x15,0x80) Enable drdy interrupt on new data

        // Done Initializations

        let scale_factor_a = accel_range / 32767f64 / 4.0f64; // m/s^2
        let scale_factor_g = gyro_range / 32767f64; // to rad/s

        loop {
            self.drdy_g.wait_for_rising_edge().await;

            self.jumper.set_high();
            Timer::after_micros(60).await;
            self.jumper.set_low();

            let timestamp = Instant::now();

            // read temperature, ax, and ay
            const BMI_ACCEL_CMD: u8 = 0x12;
            const BMI_ACCEL_BYTES: usize = 20;
            let mut rx = [0u8; BMI_ACCEL_BYTES];
            let mut tx = [0u8; BMI_ACCEL_BYTES];
            tx[0] = BMI_ACCEL_CMD | SPI_READ;
            let _ = self.dev_a.transfer(&mut rx, &tx).await;

            let seq = ((rx[8] as u64 | (rx[9] as u64) << 8 | (rx[10] as u64) << 16) * 625u64
                / 16u64) as u32; // 625/64 = 39.0625us/count
            let mut temperature = ((rx[18] as u32) << 3 | (((rx[19] as u32) >> 6) & 0x0003)) as f32;

            if temperature > 1023.0 {
                temperature -= 2048.0;
            }

            temperature *= 0.125;
            temperature += 23.0; // + 273.15; // K

            let mut accel = [0f64; 3];
            accel[0] = scale_factor_a * (((rx[15] as i16) << 8 | (rx[14] as i16)) as f64);
            accel[1] = scale_factor_a * (((rx[17] as i16) << 8 | (rx[16] as i16)) as f64);

            // Read az
            const BMI_ACCEL_SYNC_CMD: u8 = 0x27;
            const BMI_ACCEL_SYNC_BYTES: usize = 4;
            let mut rx = [0u8; BMI_ACCEL_SYNC_BYTES];
            let mut tx = [0u8; BMI_ACCEL_SYNC_BYTES];
            tx[0] = BMI_ACCEL_SYNC_CMD | SPI_READ;
            let _ = self.dev_a.transfer(&mut rx, &tx).await;

            accel[2] = scale_factor_a * (((rx[3] as i16) << 8 | (rx[2] as i16)) as f64);

            // Read gyro
            const BMI_GYRO_CMD: u8 = 0x02;
            const BMI_GYRO_BYTES: usize = 7;
            let mut rx = [0u8; BMI_GYRO_BYTES];
            let mut tx = [0u8; BMI_GYRO_BYTES];
            tx[0] = BMI_GYRO_CMD | SPI_READ;
            let _ = self.dev_g.transfer(&mut rx, &tx).await;

            let mut gyro = [0f64; 3];
            gyro[0] = scale_factor_g * (((rx[2] as i16) << 8 | (rx[1] as i16)) as f64);
            gyro[1] = scale_factor_g * (((rx[4] as i16) << 8 | (rx[3] as i16)) as f64);
            gyro[2] = scale_factor_g * (((rx[6] as i16) << 8 | (rx[5] as i16)) as f64);

            for axis in 0..3 {
                accel[axis] *= self.board_axis_signs[axis];
                gyro[axis] *= self.board_axis_signs[axis];
            }

            let status = 0u16; // dummy value
            let header = packets::RosflightPacketHeader {
                timestamp: timestamp.as_micros(),
                status,
            };
            let imu_packet = packets::ImuPacket {
                header,
                accel,
                gyro,
                temperature,
                seq,
            };
            IMU_SIGNAL.signal(Ok(imu_packet));
        }
    }
}

#[embassy_executor::task]
pub async fn task(mut bmi: Bmi08xSensor) {
    bmi.run().await;
}
